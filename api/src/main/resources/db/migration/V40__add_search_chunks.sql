-- The text "Ask the desk" reads: mail, board posts, cargoes and vessel positions, cut into chunks
-- and embedded, one row per chunk.
--
-- Chunks rather than whole documents, because a question is answered from the passage that says
-- it, not from the whole of a forty-message chain. A chunk carries its document's header lines
-- (subject, sender, date; the board's name; the vessel's name) so that a chunk read on its own
-- still says what it is about.
--
-- Vector and keyword in one table. The vector answers "what is this about" when the words differ
-- ("open tonnage Adriatic" against "SPOT ADRIATIC 1/3 SEPT"); the tsvector answers "which exact
-- name or figure" when the vector cannot tell two similar hulls apart. Both are asked, and the
-- results are fused in the application, so one row carries both.
--
-- source_kind and source_id name the record the text came from (MAIL = mail_messages.id, POST =
-- feed_items.id, CARGO = cargoes.id, POSITION = vessel_positions.id). There is no foreign key to
-- them: the source tables are not all of one kind, and a chunk of a deleted message is removed by
-- the indexer's prune pass rather than cascaded, so a delete elsewhere never waits on this table.
--
-- The rule that makes this cheap to keep current is in the indexer, not here: mail and posts are
-- immutable once stored, so a source needs indexing only when it has no chunk; cargoes and
-- positions also when their updated_at has moved past source_updated_at. Nothing in this table
-- is read to decide that - the decision is made from ids.
--
-- CREATE EXTENSION as in V38: a no-op where it is already there.
CREATE EXTENSION IF NOT EXISTS vector;

CREATE TABLE public.search_chunks (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- The desk, as every desk table has it (V31). No default, on purpose.
    tenant_id         bigint NOT NULL REFERENCES public.tenants (id),

    -- MAIL, POST, CARGO or POSITION. Text rather than an enum type, as the rest of the schema
    -- does: a fifth kind is a line in Java.
    source_kind       varchar(16) NOT NULL,
    source_id         bigint NOT NULL,

    -- Position of this chunk in its document, from 0. A document too long for one chunk has
    -- several; re-indexing a document replaces all of them at once.
    chunk_no          int NOT NULL,

    -- The mailbox owner, for MAIL only. A mail chunk is visible to its owner and to colleagues
    -- only where the desk shares the message (Mailbox rules in CLAUDE.md); every other kind is
    -- the whole desk's, so this stays null for it.
    owner_user_id     bigint REFERENCES public.users (id),

    -- The date the text is shown under: sent or received for mail, published or fetched for a
    -- post, received for a cargo, reported for a position. Shown beside each source, and never
    -- used to rank, so a plain timestamp is enough.
    source_date       timestamp,

    -- For CARGO and POSITION: the updated_at of the record when this chunk was made. The indexer
    -- compares it with the record's current updated_at, by id, to find a changed record without
    -- reading its text. Null for the immutable kinds.
    source_updated_at timestamptz,

    title             text,
    content           text NOT NULL,

    -- The embedding model this vector was computed by. Vectors from two models are not compared,
    -- and the keyword search is restricted to the same model so one passage is found once.
    model             varchar(100) NOT NULL,

    -- No dimension and no ANN index, as V38: a desk's corpus is a few tens of thousands of chunks
    -- at most, and an exact scan over those is well inside what a question can wait for. Changing
    -- the embedding model is then a re-index rather than a migration.
    embedding         vector NOT NULL,

    -- The keyword side. Generated from title and content so the two can never disagree about what
    -- a chunk says. 'simple' rather than a language configuration: the mail is English, Russian,
    -- Greek and Turkish by turns, and 'simple' does not stem a name like "Chornomorsk" into
    -- something else.
    tsv               tsvector GENERATED ALWAYS AS
                          (to_tsvector('simple', coalesce(title, '') || ' ' || content)) STORED,

    created_at        timestamptz NOT NULL DEFAULT now(),

    -- One document, one model, one set of chunks. Re-indexing a document is a delete of its rows
    -- and an insert of new ones, and this constraint is what makes a half-written document
    -- impossible to mistake for a whole one.
    CONSTRAINT ux_search_chunks_document UNIQUE (tenant_id, source_kind, source_id, chunk_no, model)
);

-- The keyword search, and the one index this table needs to find a desk's rows by their source.
CREATE INDEX ix_search_chunks_tsv ON public.search_chunks USING gin (tsv);
CREATE INDEX ix_search_chunks_source ON public.search_chunks (tenant_id, source_kind, source_id);

-- The same wall V36 put round every desk table: the database refuses another desk's chunks even
-- for plain SQL. A new table is empty, so no app.rls_bypass line is needed.
ALTER TABLE public.search_chunks ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.search_chunks FORCE ROW LEVEL SECURITY;
CREATE POLICY desk_rows ON public.search_chunks
    USING (current_setting('app.rls_bypass', true) = 'on'
           OR tenant_id = nullif(current_setting('app.tenant_id', true), '')::bigint)
    WITH CHECK (current_setting('app.rls_bypass', true) = 'on'
           OR tenant_id = nullif(current_setting('app.tenant_id', true), '')::bigint);
