-- Accounts, and the desks they belong to.
--
-- Until now there was one credential, held in the environment, and nothing in the database
-- knew who anybody was. That stops being enough the moment a second desk shares the
-- deployment: each person logs in as themselves, and what they can see is decided by the
-- desk (tenant) they belong to.
--
-- Tenant 1 is created here and is the desk this database already holds. Every row that
-- exists today belongs to it - the migrations that add tenant_id to the business tables
-- backfill to 1 - so an existing deployment upgrades into a one-tenant installation that
-- behaves exactly as before.
--
-- No user is inserted. A password hash cannot be produced in SQL without inventing one, so
-- the first account is created by the application at startup from AUTH_USERNAME and
-- AUTH_PASSWORD / AUTH_PASSWORD_HASH (UserBootstrap), the same variables that used to be the
-- only credential. After that the environment no longer decides any password.
CREATE TABLE public.tenants (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        varchar(200) NOT NULL,
    status      varchar(20)  NOT NULL DEFAULT 'ACTIVE',
    created_at  timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT ck_tenants_status CHECK (status IN ('ACTIVE', 'SUSPENDED'))
);

CREATE UNIQUE INDEX ux_tenants_name ON public.tenants (lower(name));

