-- A login name is unique across the whole installation, not per tenant. That is what lets
-- the login screen stay two fields: with names unique per desk, somebody would have to say
-- which desk they are before saying who they are.
--
-- The lockout counters live on the row rather than in memory: they survive a restart, and
-- one person mistyping does not lock everybody else out, which a single counter did.
--
-- token_version is what makes a stateless token revocable where it matters. It is carried in
-- every token and compared on every request; disabling an account, resetting its password or
-- changing its role bumps it, and every token issued before that stops working at once.
CREATE TABLE public.users (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id             bigint       NOT NULL REFERENCES public.tenants (id),
    username              varchar(150) NOT NULL,
    display_name          varchar(200),
    password_hash         varchar(100) NOT NULL,
    role                  varchar(20)  NOT NULL,
    enabled               boolean      NOT NULL DEFAULT true,
    must_change_password  boolean      NOT NULL DEFAULT false,
    failed_attempts       integer      NOT NULL DEFAULT 0,
    locked_until          timestamptz,
    token_version         integer      NOT NULL DEFAULT 0,
    last_login_at         timestamptz,
    created_at            timestamptz  NOT NULL DEFAULT now(),
    created_by            varchar(150),
    CONSTRAINT ck_users_role CHECK (role IN ('PLATFORM_ADMIN', 'TENANT_ADMIN', 'USER'))
);

CREATE UNIQUE INDEX ux_users_username ON public.users (lower(username));
CREATE INDEX ix_users_tenant ON public.users (tenant_id);
